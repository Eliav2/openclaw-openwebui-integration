#!/usr/bin/env python3
"""The notification's two images, drawn from one crab claw outline and written into oc-sw.js as data: URLs.

- badge: Android's small icon (status bar, the notification's header). Android uses only its alpha,
  as a mask, so it is the claw in white on transparent; an opaque image shows as a square.
- icon: the larger picture beside the text, in colour.

They live in the service worker itself: Open WebUI rebuilds /static on every start, and a separate
file would need its own route in the proxy (and, behind Cloudflare Access, its own bypass).

usage: uv run --with cairosvg==2.9.1 --with pillow python3 push/web/icons/make_icons.py
"""
import base64
import io
import os
import re

import cairosvg
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SW = os.path.join(os.path.dirname(HERE), "oc-sw.js")
BADGE_PX = 96
ICON_PX = 192
ICON_COLOURS = 32   # a palette PNG: a fraction of the size, the same look
BEGIN, END = "// --- icons: generated by push/web/icons/make_icons.py, do not edit", "// --- end icons"


def svg(name):
    return open(os.path.join(HERE, name)).read().encode()


def png(name, px, colours=None):
    raw = cairosvg.svg2png(bytestring=svg(name), output_width=px, output_height=px)
    if colours:
        im = Image.open(io.BytesIO(raw)).quantize(colours, method=Image.Quantize.FASTOCTREE)
        buf = io.BytesIO(); im.save(buf, "PNG", optimize=True); raw = buf.getvalue()
    return "data:image/png;base64," + base64.b64encode(raw).decode()


def main():
    block = "\n".join([BEGIN,
                       f'const BADGE = "{png("badge.svg", BADGE_PX)}";',
                       f'const ICON = "{png("icon.svg", ICON_PX, ICON_COLOURS)}";',
                       END])
    src = open(SW).read()
    out, n = re.subn(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, src, flags=re.S)
    assert n == 1, "oc-sw.js has no icons block"
    open(SW, "w").write(out)
    print(f"oc-sw.js: badge {BADGE_PX}px, icon {ICON_PX}px, block {len(block)} chars")


if __name__ == "__main__":
    main()
