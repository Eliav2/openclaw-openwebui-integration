#!/usr/bin/env python3
"""Fail when the vendored Open WebUI frontend reducer no longer matches upstream.

`test_fixture_owui_structured_output.ts` is a verbatim copy of the part of
Open WebUI's `structuredOutput.ts` that folds Responses stream events into the
output list a chat tab renders live (`applyResponseStreamEvent` and what it
calls). The live-order tests run it with bun, so they pin what the browser
does, not our belief about it: the backend appends an `output_item.added`
that has no `output_index`, while this reducer splices it in before the last
item, and that difference put a tool card above the text written before it
(ELI-122).

The copy is generated by this script (`--print-upstream`), never hand-edited;
the check compares each declaration's text against a given Open WebUI ref. CI checks the copy the
tests run against the pinned ref (--copy pinned) and the next release's own copy against its ref
(--copy next); the compat watch passes a ref when any copy (the pinned release's, plus one per later
release whose reducer changed) matches.

Usage:
  python3 scripts/check_owui_frontend_fixture.py --ref v0.12.0
  python3 scripts/check_owui_frontend_fixture.py --ref v0.12.0 --print-upstream  # re-extract
  python3 scripts/check_owui_frontend_fixture.py --ref v0.12.5 --copy pinned  # CI: the copy the tests run

Exit status: 0 match, 1 drift, 2 could not fetch or find a declaration.
"""

from __future__ import annotations

import argparse
import difflib
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "test_fixture_owui_structured_output.ts"
# The pinned release's copy (above) is the one the tests run. A release whose reducer changed gets its
# own copy next to it (..._v0.12.4.ts), so the compat watch can match "latest" and "main" while CI
# stays on the pin.
FIXTURES = sorted(FIXTURE.parent.glob("test_fixture_owui_structured_output*.ts"))


def versioned_suffix(ref: str) -> str:
    return "_" + ref
UPSTREAM = ("https://raw.githubusercontent.com/open-webui/open-webui/{ref}/"
            "src/lib/components/chat/Messages/structuredOutput.ts")
MARKER = "// ---- verbatim from upstream below this line ----\n"
DECLARATIONS = ("OutputContentPart", "OutputItem", "ResponseStreamEvent", "appendDelta",
                "ensureOutputItem", "ensurePart", "setPart", "findOutputItemIndex",
                "responseEventUpdatesOutputItem", "applyResponseStreamEvent")


def declaration(source: str, name: str) -> str:
    """The top-level `type`/`function` declaration `name`, from its first
    line to the closing brace at column 0."""
    lines = source.split("\n")
    heads = (f"function {name}(", f"type {name} =")
    for i, line in enumerate(lines):
        if line.removeprefix("export ").startswith(heads):
            for j in range(i, len(lines)):
                if lines[j] in ("}", "};"):
                    return "\n".join(lines[i:j + 1])
    raise LookupError(f"{name} not found")


def extract(source: str) -> str:
    return "\n\n".join(declaration(source, n) for n in DECLARATIONS) + "\n"


def copies_to_check(ref: str, which: str) -> list[Path] | str:
    """The copies a ref is checked against, or why the check cannot run.
    "pinned": only the unversioned copy, the one the tests run (and no copy
    may be versioned for the pinned ref: that copy should have replaced it).
    "next": the ref's own versioned copy, else the unversioned one.
    "any": every copy (the compat watch, on latest and main)."""
    own = [p for p in FIXTURES if p != FIXTURE and p.stem.endswith(versioned_suffix(ref))]
    if which == "pinned":
        if own:
            return (f"{own[0].name} is for the pinned {ref}: move it into {FIXTURE.name} "
                    "(the copy the tests run) and delete it")
        return [FIXTURE]
    if which == "next":
        return own or [FIXTURE]
    return FIXTURES


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ref", required=True, help="Open WebUI git ref (tag, branch, sha)")
    parser.add_argument("--print-upstream", action="store_true",
                        help="print the upstream declarations and exit")
    parser.add_argument("--copy", choices=("any", "pinned", "next"), default="any",
                        help="pinned: only the copy the tests run; next: the ref's own copy, else "
                             "that one; any: every copy (default, the compat watch)")
    args = parser.parse_args()
    copies = copies_to_check(args.ref, args.copy)
    if isinstance(copies, str):
        print(copies, file=sys.stderr)
        return 1

    url = UPSTREAM.format(ref=args.ref)
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            upstream = extract(resp.read().decode())
    except urllib.error.URLError as exc:
        print(f"could not fetch {url}: {exc}", file=sys.stderr)
        return 2
    except LookupError as exc:
        print(f"{url}: {exc}", file=sys.stderr)
        return 2

    if args.print_upstream:
        print(upstream, end="")
        return 0

    drift = []
    for path in copies:
        fixture = path.read_text()
        if MARKER not in fixture:
            print(f"{path.name}: missing the verbatim marker line", file=sys.stderr)
            return 2
        vendored = fixture.split(MARKER, 1)[1]
        if vendored == upstream:
            print(f"{path.name} matches open-webui@{args.ref}")
            return 0
        drift.append((path, vendored))
    path, vendored = drift[0]
    sys.stdout.writelines(difflib.unified_diff(
        vendored.splitlines(True), upstream.splitlines(True),
        f"{path.name} (vendored)", f"open-webui@{args.ref}"))
    print(f"\n{', '.join(p.name for p, _ in drift)} drifted from open-webui@{args.ref}: re-extract with "
          "--print-upstream and re-run the live-order tests.", file=sys.stderr)
    return 1

if __name__ == "__main__":
    sys.exit(main())
