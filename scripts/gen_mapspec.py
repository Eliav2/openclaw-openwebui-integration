#!/usr/bin/env python3
"""Generate src/openclaw_pipe_pkg/mapspec.py, the Pipe's types for the Gateway plugin `map`, from
schemas/map-spec.schema.json (a copy of gateway-plugins/map/map-spec.schema.json in the
openclaw-workspace repo, where the plugin's own types are generated from the original).

  python3 scripts/gen_mapspec.py          write the fragment
  python3 scripts/gen_mapspec.py --check  exit 1 if the fragment is stale (CI)

Needs datamodel-code-generator: uvx --from datamodel-code-generator python scripts/gen_mapspec.py
"""
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schemas" / "map-spec.schema.json"
OUT = ROOT / "src" / "openclaw_pipe_pkg" / "mapspec.py"
BANNER = (
    "# ------------------------------------------------------------------\n"
    "# BUILD FRAGMENT -- do not edit the built openclaw_pipe.py directly.\n"
    "# Source of truth: src/openclaw_pipe_pkg/<module>.py + build.py\n"
    "# ------------------------------------------------------------------\n"
    "# GENERATED by scripts/gen_mapspec.py from schemas/map-spec.schema.json: do not edit.\n"
    "# schema-sha256: {digest}\n\n"
)
SKIPPED_LINES = ("from __future__", "#", "from typing import")
CHECK_FLAG = "--check"
TYPING_IMPORT = "from typing import Literal, NotRequired, TypeAlias, TypedDict\n"


def schema_digest() -> str:
    return hashlib.sha256(SCHEMA.read_bytes()).hexdigest()


def generate() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "types.py"
        subprocess.run(
            ["datamodel-codegen", "--input", str(SCHEMA), "--input-file-type", "jsonschema",
             "--output-model-type", "typing.TypedDict", "--target-python-version", "3.11",
             "--no-use-closed-typed-dict", "--disable-timestamp", "--output", str(raw)],
            check=True, capture_output=True)
        body = "".join(line for line in raw.read_text().splitlines(keepends=True)
                       if not line.startswith(SKIPPED_LINES)).lstrip("\n")
    return BANNER.format(digest=schema_digest()) + TYPING_IMPORT + "\n\n" + body


def main() -> int:
    text = generate()
    if CHECK_FLAG in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen_mapspec.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
